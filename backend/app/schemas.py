"""Pydantic request/response schemas for the ScreenWise API.

Field ranges are based on the actual dataset (see artifacts/feature_info.json,
generated by ml/train.py from ScreenTime vs MentalWellness.csv).
"""
from typing import Literal, Optional

from pydantic import BaseModel, ConfigDict, Field


class PredictionRequest(BaseModel):
    age: int = Field(..., ge=10, le=100, description="Age in years")
    gender: Literal["Female", "Male", "Non-binary/Other"]
    occupation: Literal["Employed", "Retired", "Self-employed", "Student", "Unemployed"]
    work_mode: Literal["Hybrid", "In-person", "Remote"]
    screen_time_hours: float = Field(..., ge=0, le=24, description="Total daily screen time (hours)")
    work_screen_hours: float = Field(..., ge=0, le=24, description="Work-related screen time (hours/day)")
    leisure_screen_hours: float = Field(..., ge=0, le=24, description="Leisure screen time (hours/day)")
    sleep_hours: float = Field(..., ge=0, le=24, description="Average nightly sleep (hours)")
    exercise_minutes_per_week: float = Field(..., ge=0, le=1000, description="Exercise minutes per week")
    social_hours_per_week: float = Field(..., ge=0, le=168, description="Social time per week (hours)")

    model_config = ConfigDict(
        json_schema_extra={
            "example": {
                "age": 24,
                "gender": "Female",
                "occupation": "Student",
                "work_mode": "Remote",
                "screen_time_hours": 8.5,
                "work_screen_hours": 3.0,
                "leisure_screen_hours": 5.5,
                "sleep_hours": 6.5,
                "exercise_minutes_per_week": 90,
                "social_hours_per_week": 6.0,
            }
        }
    )


class TopFactor(BaseModel):
    feature: str
    importance: float


class PredictionResponse(BaseModel):
    prediction: Literal["Low", "Moderate", "High"]
    score: float
    confidence: Optional[float] = None
    top_factors: list[TopFactor]


class HealthResponse(BaseModel):
    status: str
    model_loaded: bool


class ModelInfoResponse(BaseModel):
    model_name: str
    training_date: str
    dataset: str
    random_state: int
    features: list[str]
    metrics: dict
    target_construction: str
